import fs from "node:fs";
import path from "node:path";
import { ROOT, write, copyTemplate, str, hex } from "./util.mjs";

const mi = (spec, key) => `Icons.Filled.${spec.icons[key]?.android || "Info"}`;
const kstr = (s) => str(s).replaceAll("$", "\\$");

export function generateAndroid(spec, dir) {
  const android = path.join(dir, "android");
  const pkg = spec.android.packageName;
  const { content: c, brand: b } = spec;
  copyTemplate(path.join(ROOT, "templates/android"), android, {
    PACKAGE: pkg,
    PKGDIR: pkg.replaceAll(".", "/"),
    MODULE: spec.ios.target.replace(/App$/, "Android"),
    COMPANY: spec.company.replace(/[<&"]/g, ""),
    MIN_SDK: String(spec.android.minSdk),
    COMPILE_SDK: String(spec.android.compileSdk),
  });
  const src = path.join(android, "app/src/main/java", ...pkg.split("."));

  write(path.join(src, "Theme.kt"), `// Generated by parity-studio from spec.json. Do not edit by hand.
package ${pkg}

import androidx.compose.ui.graphics.Color

object Brand {
    const val name = ${kstr(spec.company)}
    val primary = Color(0xFF${hex(b.primary)})
    val accent = Color(0xFF${hex(b.accent)})
    val highlight = Color(0xFF${hex(b.highlight)})
    val surface = Color(0xFF${hex(b.surface)})
    val onPrimary = Color(0xFF${hex(b.onPrimary)})
    val ink = Color(0xFF1C1B1F)
    val muted = Color(0xFF6B6670)
    val success = Color(0xFF1E8E5A)
}
`);

  const item = (it) => `ItemContent(${kstr(it.title)}, ${kstr(it.subtitle)}, ${kstr(it.value)}, ${kstr(it.badge)}, ${mi(spec, it.icon)})`;
  write(path.join(src, "Content.kt"), `// Generated by parity-studio from spec.json. Do not edit by hand.
package ${pkg}

import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.ui.graphics.vector.ImageVector

data class TabContent(val id: String, val title: String, val icon: ImageVector)
data class HeroContent(val eyebrow: String, val title: String, val subtitle: String, val cta: String)
data class StatContent(val label: String, val value: String, val icon: ImageVector)
data class ItemContent(val title: String, val subtitle: String, val value: String, val badge: String, val icon: ImageVector)
data class DetailContent(val optionsTitle: String, val options: List<String>, val primaryAction: String, val confirmation: String)
data class RowContent(val title: String, val icon: ImageVector)
data class AccountContent(val name: String, val subtitle: String, val rows: List<RowContent>, val toggle: String)

object Content {
    const val greeting = ${kstr(c.greeting)}
    val tabs = listOf(
${c.tabs.map((t) => `        TabContent(${kstr(t.id)}, ${kstr(t.title)}, ${mi(spec, t.icon)}),`).join("\n")}
    )
    val hero = HeroContent(${kstr(c.hero.eyebrow)}, ${kstr(c.hero.title)}, ${kstr(c.hero.subtitle)}, ${kstr(c.hero.cta)})
    val stats = listOf(
${c.stats.map((s) => `        StatContent(${kstr(s.label)}, ${kstr(s.value)}, ${mi(spec, s.icon)}),`).join("\n")}
    )
    const val sectionTitle = ${kstr(c.sectionTitle)}
    const val searchPlaceholder = ${kstr(c.searchPlaceholder)}
    val items = listOf(
${c.items.map((it) => `        ${item(it)},`).join("\n")}
    )
    val detail = DetailContent(${kstr(c.detail.optionsTitle)}, listOf(${c.detail.options.map(kstr).join(", ")}), ${kstr(c.detail.primaryAction)}, ${kstr(c.detail.confirmation)})
    val account = AccountContent(${kstr(c.account.name)}, ${kstr(c.account.subtitle)}, listOf(
${c.account.rows.map((r) => `        RowContent(${kstr(r.title)}, ${mi(spec, r.icon)}),`).join("\n")}
    ), ${kstr(c.account.toggle)})
}
`);
  write(path.join(android, "app/src/test/resources/parity-spec.json"), JSON.stringify(spec, null, 2));
  return android;
}
