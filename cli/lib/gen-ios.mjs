import path from "node:path";
import { ROOT, write, copyTemplate, str, hex } from "./util.mjs";

const sf = (spec, key) => spec.icons[key]?.ios || "circle.fill";

export function generateIOS(spec, dir) {
  const ios = path.join(dir, "ios");
  const { content: c, brand: b } = spec;
  const target = spec.ios.target;
  copyTemplate(path.join(ROOT, "templates/ios"), ios);

  write(path.join(ios, "Sources/Theme.swift"), `// Generated by parity-studio from spec.json. Do not edit by hand.
import SwiftUI

enum Brand {
    static let name = ${str(spec.company)}
    static let primary = Color(hex: 0x${hex(b.primary)})
    static let accent = Color(hex: 0x${hex(b.accent)})
    static let highlight = Color(hex: 0x${hex(b.highlight)})
    static let surface = Color(hex: 0x${hex(b.surface)})
    static let onPrimary = Color(hex: 0x${hex(b.onPrimary)})
    static let ink = Color(hex: 0x1C1B1F)
    static let muted = Color(hex: 0x6B6670)
    static let success = Color(hex: 0x1E8E5A)
}

extension Color {
    init(hex: UInt32) {
        self.init(red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255)
    }
}
`);

  const item = (it) => `ItemContent(title: ${str(it.title)}, subtitle: ${str(it.subtitle)}, value: ${str(it.value)}, badge: ${str(it.badge)}, icon: ${str(sf(spec, it.icon))})`;
  write(path.join(ios, "Sources/Content.swift"), `// Generated by parity-studio from spec.json. Do not edit by hand.
import Foundation

struct TabContent { let id: String; let title: String; let icon: String }
struct HeroContent { let eyebrow: String; let title: String; let subtitle: String; let cta: String }
struct StatContent { let label: String; let value: String; let icon: String }
struct ItemContent { let title: String; let subtitle: String; let value: String; let badge: String; let icon: String }
struct DetailContent { let optionsTitle: String; let options: [String]; let primaryAction: String; let confirmation: String }
struct RowContent { let title: String; let icon: String }
struct AccountContent { let name: String; let subtitle: String; let rows: [RowContent]; let toggle: String }

enum Content {
    static let greeting = ${str(c.greeting)}
    static let tabs: [TabContent] = [
${c.tabs.map((t) => `        TabContent(id: ${str(t.id)}, title: ${str(t.title)}, icon: ${str(sf(spec, t.icon))}),`).join("\n")}
    ]
    static let hero = HeroContent(eyebrow: ${str(c.hero.eyebrow)}, title: ${str(c.hero.title)}, subtitle: ${str(c.hero.subtitle)}, cta: ${str(c.hero.cta)})
    static let stats: [StatContent] = [
${c.stats.map((s) => `        StatContent(label: ${str(s.label)}, value: ${str(s.value)}, icon: ${str(sf(spec, s.icon))}),`).join("\n")}
    ]
    static let sectionTitle = ${str(c.sectionTitle)}
    static let searchPlaceholder = ${str(c.searchPlaceholder)}
    static let items: [ItemContent] = [
${c.items.map((it) => `        ${item(it)},`).join("\n")}
    ]
    static let detail = DetailContent(optionsTitle: ${str(c.detail.optionsTitle)}, options: ${str(c.detail.options)}, primaryAction: ${str(c.detail.primaryAction)}, confirmation: ${str(c.detail.confirmation)})
    static let account = AccountContent(name: ${str(c.account.name)}, subtitle: ${str(c.account.subtitle)}, rows: [
${c.account.rows.map((r) => `        RowContent(title: ${str(r.title)}, icon: ${str(sf(spec, r.icon))}),`).join("\n")}
    ], toggle: ${str(c.account.toggle)})
}
`);

  write(path.join(ios, "UITests/parity-spec.json"), JSON.stringify(spec, null, 2));

  write(path.join(ios, "project.yml"), `# Generated by parity-studio. Regenerate the Xcode project with: xcodegen generate
name: ${target}
options:
  bundleIdPrefix: com.paritystudio
  deploymentTarget:
    iOS: "${spec.ios.deploymentTarget}"
targets:
  ${target}:
    type: application
    platform: iOS
    sources: [Sources]
    settings:
      base:
        PRODUCT_BUNDLE_IDENTIFIER: ${spec.ios.bundleId}
        PRODUCT_NAME: ${target}
        MARKETING_VERSION: "1.0.0"
        CURRENT_PROJECT_VERSION: "1"
        GENERATE_INFOPLIST_FILE: YES
        INFOPLIST_KEY_CFBundleDisplayName: ${str(spec.company)}
        INFOPLIST_KEY_UILaunchScreen_Generation: YES
        INFOPLIST_KEY_UISupportedInterfaceOrientations: UIInterfaceOrientationPortrait
        INFOPLIST_KEY_UIUserInterfaceStyle: Light
        CODE_SIGN_IDENTITY: "-"
        CODE_SIGNING_ALLOWED: NO
        SWIFT_VERSION: "5.0"
  ${target}UITests:
    type: bundle.ui-testing
    platform: iOS
    sources:
      - path: UITests
        excludes: ["*.json"]
      - path: UITests/parity-spec.json
        buildPhase: resources
    dependencies:
      - target: ${target}
    settings:
      base:
        PRODUCT_BUNDLE_IDENTIFIER: ${spec.ios.bundleId}.uitests
        GENERATE_INFOPLIST_FILE: YES
        TEST_TARGET_NAME: ${target}
        CODE_SIGN_IDENTITY: "-"
        CODE_SIGNING_ALLOWED: NO
        SWIFT_VERSION: "5.0"
schemes:
  ${target}:
    build:
      targets:
        ${target}: all
        ${target}UITests: [test]
    test:
      targets: [${target}UITests]
`);
  write(path.join(ios, ".gitignore"), "*.xcodeproj/\nbuild/\n");
  return ios;
}
